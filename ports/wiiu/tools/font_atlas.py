#!/usr/bin/env python3
"""The GamePad debug menu's font atlas (ports/wiiu/game/debug_menu.cpp), made at build time from a monospaced TrueType font on the
building machine (DejaVu Sans Mono by default): ASCII 32..127 in 16 x 6 cells of 10 x 20 pixels, one coverage byte a pixel, written
as a C++ header into the build folder (generated: never committed).

    python3 ports/wiiu/tools/font_atlas.py <out.h> [font.ttf]
"""
import sys

CELL_W, CELL_H, COLS, ROWS = 10, 20, 16, 6


def main():
    out = sys.argv[1]
    font_path = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
    w, h = CELL_W * COLS, CELL_H * ROWS
    data = bytes(w * h)
    ok = 0
    try:
        from PIL import Image, ImageDraw, ImageFont

        font = ImageFont.truetype(font_path, 16)
        img = Image.new("L", (w, h), 0)
        d = ImageDraw.Draw(img)
        for c in range(32, 128):
            i = c - 32
            d.text(((i % COLS) * CELL_W, (i // COLS) * CELL_H + 1), chr(c), fill=255, font=font)
        data = img.tobytes()
        ok = 1
    except Exception as e:  # (no PIL or no font: an empty atlas, the menu's boxes without text)
        print(f"font_atlas.py: no font ({e}): the menu's text left out", file=sys.stderr)
    with open(out, "w") as f:
        f.write("// Generated by ports/wiiu/tools/font_atlas.py: the debug menu's font atlas (never committed)\n#pragma once\n#include <cstdint>\n")
        f.write(f"constexpr int kFontCellW = {CELL_W}, kFontCellH = {CELL_H}, kFontCols = {COLS}, kFontRows = {ROWS}, kFontOk = {ok};\n")
        f.write(f"constexpr int kFontW = {w}, kFontH = {h};\nconst uint8_t kFontAtlas[{w * h}] = {{\n")
        for r in range(0, len(data), 32):
            f.write(",".join(str(b) for b in data[r:r + 32]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
