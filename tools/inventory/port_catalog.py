def esc(t):
    return (t or "").replace("|", "\\|").replace("\n", " ")


def kb(n):
    return D.kb(n)


def compress_images(ims):
    """`every level`, `front, L0-L4, L7`, ..."""
    ims = set(ims)
    lv = sorted(int(x[1:]) for x in ims if x.startswith("L"))
    out = [x for x in ("core", "front") if x in ims]
    if len(lv) == 19:
        out.append("every level")
    else:
        i = 0
        while i < len(lv):
            j = i
            while j + 1 < len(lv) and lv[j + 1] == lv[j] + 1:
                j += 1
            out.append("L%d" % lv[i] if i == j else "L%d-L%d" % (lv[i], lv[j]) if j > i + 1 else
                       "L%d, L%d" % (lv[i], lv[j]))
            i = j + 1
    return ", ".join(out)


def link(path, depth=2):
    """A repository path, linked relative from docs/catalog/ (generated files: not in the repository, not linked)."""
    if path.startswith("gen:"):
        return "`assets/generated/%s` (generated)" % path[4:]
    up = "../" * depth
    label = path.rstrip("/").split("/")[-1] + ("/" if path.endswith("/") else "") if path.count("/") > 2 else path
    return "[`%s`](%s%s)" % (label, up, path)


def file_rank(p):
    gen = p.startswith("gen:")
    hdr = p.endswith(".h")
    return (hdr, gen, p)


