class Cat:
    def __init__(self, out):
        self.R, self.P, self.C, self.S = load(out)
        self.notes = D.read_notes()
        self.U, self.by_copy, _ev = D.unique_functions(self.R, self.notes)
        self.copy = {(r["image"], int(r["addr"], 16)): r for r in self.R}
        self.ports = collections.defaultdict(list)
        for p in self.P:
            path = ("gen:" if p["generated"] == "1" else "") + p["file"]
            self.ports[(p["image"], int(p["addr"], 16))].append(dict(p, path=path))
        self.batches = oracle_batches(self.R)
        self.marks, self.todo = source_markers()
        for u in self.U:
            self.fill(u)
        self.core = []
        for r in sorted((r for r in self.R if r["image"] == "core"), key=lambda r: r["addr"]):
            self.core.append(self.core_row(r))

    def keys_of(self, rows):
        ks = [(r["image"], int(r["addr"], 16)) for r in rows]
        for r in rows:  # the Veldin port a copy runs through (matched, translated, a stand-in)
            if r["veldin"] and r["image"] not in ("L0", "core") and (r["status"] == "ported" or r["standin_of"]):
                ks.append(("L0", int(r["veldin"], 16)))
        return list(dict.fromkeys(ks))

    def port_info(self, keys):
        sites = [s for k in keys for s in self.ports.get(k, ())]
        files = sorted({s["path"] for s in sites}, key=file_rank)
        own = [f for f in files if not f.endswith(".h")] or files
        desc = ""
        for s in sorted(sites, key=lambda s: (s["kind"] != "orig", s["partial"], file_rank(s["path"]), int(s["line"] or 0))):
            if s["desc"] and s["kind"] != "registered":
                desc = s["desc"]
                break
        name = next((s["name"] for s in sorted(sites, key=lambda s: (s["partial"], file_rank(s["path"]))) if s["name"]),
                    "")
        bt = set()
        for k in keys:
            bt |= self.batches.get(k, set())
        for s in sites:
            bt |= comment_batches(s["desc"])
        kinds = {s["kind"] for s in sites}
        return own, desc, name, bt, kinds

    def how_of(self, keys):
        """How a port is written: `hand` (a hand-written port in the repository: an `// orig:` of a .cpp of src/, or of a
        header only when nothing else ports it), `generated` (translated at setup into assets/generated/; a hand-written
        registration or header declaration around it does not count), `both` (a generated body and a hand-written
        `// orig:` port in a .cpp for the same function: glue, an override, a variant); empty when no port names it."""
        sites = [s for k in keys for s in self.ports.get(k, ())]
        gen = any(s["generated"] == "1" for s in sites)
        hand = any(s["generated"] != "1" and not s["path"].endswith(".h") and s["kind"] in ("orig", "inline")
                   for s in sites)
        hand_h = any(s["generated"] != "1" and s["path"].endswith(".h") and s["kind"] == "orig" for s in sites)
        reg = any(s["generated"] != "1" and s["kind"] == "registered" for s in sites)
        if gen and hand:
            return "both"
        if gen:
            return "generated"
        if hand or hand_h or reg:
            return "hand"
        return ""

    def fill(self, u):
        rows = sorted(u["rows"], key=lambda r: (ORDER[r["image"]], r["addr"]))
        rep = next((r for r in rows if r["image"] == "L0"), rows[0])
        if u["state"] in ("host", "debug", "unopened", "false", "left", "inprogress"):
            rep = u["rep"]  # (the copy the note and the inventory page name)
        u["show"] = rep
        u["images"] = sorted({r["image"] for r in rows}, key=lambda x: ORDER[x])
        keys = self.keys_of(rows)
        files, desc, name, bt, kinds = self.port_info(keys)
        if u["note"]:
            bt |= comment_batches(u["note"][2])
        u["files"], u["batches"] = files, sorted(bt)
        u["how"] = self.how_of(keys) if u["state"] == "ported" or u.get("ported_somewhere") else ""
        u["name"] = name or next((r["name"] for r in rows if r["name"]), "")
        st = u["state"]
        detail = ""
        if st == "ported":
            if u["note"] and u["note"][0] == "inline" or kinds == {"inline"}:
                detail = "inline"
            elif all(r["status"] == "empty" for r in rows if D.reached(r)):
                detail = "empty"
            elif not files:
                detail = "no port file"
        elif st == "dead" and u["ported_somewhere"]:
            detail = "ported anyway"
        u["detail"] = detail
        what = u["note"][2] if u["note"] else desc
        if not what:
            bits = []
            if rep["role"]:
                bits.append("the update of " + rep["role"])
            elif rep["roots"]:
                bits.append("named by the " + rep["roots"].replace("/", " / ") + " data")
            what = "; ".join(bits)
        u["what"] = what
        if st == "host":
            u["by"] = self.host_by(u)

    def host_by(self, u):
        """The host module that stands in for a function (the TODO_PORT stub's file, else the note's words)."""
        out = []
        for r in u["rows"]:
            for v in (int(r["addr"], 16), int(r["veldin"], 16) if r["veldin"] else None):
                for f, _n in sorted(self.todo.get(v, ())):
                    out.append("stub in " + link(f))
        text = u["note"][2] if u["note"] else ""
        for p in re.findall(r"\b((?:src|runtime)/[\w/.]+)", text):
            out.append(link(p.rstrip(".")))
        if not any(x.startswith("[") and "stub" not in x for x in out):
            for rx, files in HOST_RULES:
                if re.search(rx, text):
                    out += [link(f) for f in files]
                    break
        return list(dict.fromkeys(out))

    def core_row(self, r):
        a = int(r["addr"], 16)
        keys = [("core", a)]
        files, desc, name, bt, _k = self.port_info(keys)
        nt = None
        for im, lo, hi, tag, pkg, text in self.notes:
            if im == "core" and lo <= a < hi:
                nt = (tag, pkg, text)
        if r["status"] in ("ported", "empty"):
            st = "ported"
        elif not D.reached(r):
            st = "dead"
        elif nt and nt[0] in ("debug", "false"):
            st = nt[0]
        else:
            st = "hostlib"
        by = []
        for f, n in sorted(self.todo.get(a, ())):
            by.append("stub in " + link(f))
        near = r["file"].lstrip("~") if st == "hostlib" else ""
        if st == "hostlib" and not by and near:
            by.append("near " + link(near))
        how = self.how_of(keys) if st == "ported" else ""
        return dict(addr=a, size=int(r["size"]), name=name or r["name"], state=st, files=files, by=by, near=near, how=how,
                    batches=sorted(bt), what=(nt[2] if nt else desc), reach=r["reach"])

    # ---- the rows ---------------------------------------------------------------------------------------------

    def status_cell(self, u):
        s = STATUS[u["state"]]
        return s + (" (%s)" % u["detail"] if u.get("detail") else "")

    def where_cell(self, u):
        if u["state"] in ("host", "hostlib"):
            return ", ".join(u.get("by") or []) or "(see [Host replacements](host.md))"
        if not u["files"]:
            return ""
        shown = [link(f) for f in u["files"][:2]]
        if len(u["files"]) > 2:
            shown.append("+%d" % (len(u["files"]) - 2))
        return ", ".join(shown)

    def fn_row(self, u, images=True):
        r = u["show"]
        addr = "%s:0x%s" % (r["image"], r["addr"]) if r["image"] != "L0" else "0x%s" % r["addr"]
        cells = [addr, "`%s`" % u["name"] if u["name"] else "", kb(u["size"]), self.status_cell(u), u["how"],
                 self.where_cell(u), ", ".join(str(b) for b in u["batches"])]
        if images:
            cells.append(compress_images(u["images"]))
        cells.append(esc(u["what"]))
        return "| " + " | ".join(esc(c) if i < 2 else c for i, c in enumerate(cells)) + " |"


