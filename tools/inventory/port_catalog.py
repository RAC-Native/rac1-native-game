def load(out):
    R = list(csv.DictReader(open(out / "functions.csv")))
    P = list(csv.DictReader(open(out / "ports.csv"))) if (out / "ports.csv").exists() else []
    C = list(csv.DictReader(open(out / "classes.csv"))) if (out / "classes.csv").exists() else []
    S = json.loads((out / "summary.json").read_text())
    return R, P, C, S


def oracle_batches(R):
    """{(image, addr): {batch}}: the function starts a batch names (a literal address, or `Ln:0x...`), the image by the
    batch's levels (`ORACLE_LEVEL=n`, Veldin's addresses first, the boot module's for the boot module's batches)."""
    starts = collections.defaultdict(set)
    for r in R:
        starts[r["image"]].add(int(r["addr"], 16))
    out = collections.defaultdict(set)
    for p in sorted((ROOT / "tests/oracle").glob("batch_*.cpp")):
        m = re.match(r"batch_(\d+)\.cpp", p.name)
        if not m:
            continue
        n = int(m.group(1))
        t = p.read_text(errors="replace")
        lvls = {int(x) for x in re.findall(r"ORACLE_LEVEL\s*=\s*(\d+)", t)}
        boot = bool(re.search(r"boot module|front:", t))
        for m2 in re.finditer(r"\b(?:(L\d+|front):)?0x([0-9a-fA-F]{6,8})\b", t):
            a = int(m2.group(2), 16)
            if m2.group(1):
                if a in starts.get(m2.group(1), ()):
                    out[(m2.group(1), a)].add(n)
                continue
            if a < 0x15EF00:
                if a in starts["core"]:
                    out[("core", a)].add(n)
                continue
            if a in starts["L0"]:
                out[("L0", a)].add(n)
            elif boot and a in starts["front"]:
                out[("front", a)].add(n)
            for lv in lvls:
                if a in starts.get("L%d" % lv, ()) and a not in starts["L0"]:
                    out[("L%d" % lv, a)].add(n)
    return out


def comment_batches(text):
    """The batches a description names (`batch 400`, `batches 44 .. 55, 123`)."""
    out = set()
    for m in re.finditer(r"\bbatch(?:es)?\s+((?:\d+(?:\s*(?:,|and|\.\.)\s*)?)+)", text or ""):
        out |= {int(x) for x in re.findall(r"\d+", m.group(1))}
    return out


def source_markers():
    """The `// orig: (host)` / `(none)` / `(helper)` markers and the TODO_PORT stubs of the sources, per file."""
    marks = collections.defaultdict(collections.Counter)
    todo = collections.defaultdict(set)  # addr -> {(file, name)}
    for base in ("src", "runtime"):
        for p in sorted((ROOT / base).rglob("*")):
            if p.suffix not in (".cpp", ".h", ".inc"):
                continue
            rel = str(p.relative_to(ROOT))
            for line in p.read_text(errors="replace").split("\n"):
                m = re.search(r"//\s*orig:\s*\((host|none|helper)\)\s*(.*)$", line)
                if m:
                    kind = m.group(1)
                    if kind == "none" and re.search(r"\benhancement\b", m.group(2)):
                        kind = "enhancement"
                    marks[rel][kind] += 1
                for m in re.finditer(r"TODO_PORT\(\s*0x([0-9a-fA-F]+)\s*,\s*\"([^\"]*)\"", line):
                    todo[int(m.group(1), 16)].add((rel, m.group(2)))
    return marks, todo


