#!/usr/bin/env python3
"""The example level mod (docs/mods.md, "Level mods"): writes a small level of our own into a mod folder.

    python3 examples/custom-level/make_example.py [mods/example-plateau]

Then `./build/rac1-native --setup --level-mods` (or the setup) composes it with your disc, and the ship's planet list
shows "Example Plateau". Everything here is generated by this script (no game data): a floor with a checker texture,
a ramp up to a raised platform, a few blocks (their vertices coloured), a ship pad, crates (the base level's classes, by
number), another level's sky and a short tune of our own as the music, made round (0, 0, 0) and moved by level.txt's
offset line; and a plugin (plugin/: a moving platform, a HUD line, a sound, a counter in the save). The files are the level folder's
format 1: level.txt, collision.obj, meshes.obj / meshes.mtl, two PNG textures, lights.txt and plateau.vag.
"""
import json
import math
import os
import struct
import sys
import zlib


def png(path, w, h, pixel):
    """An RGB PNG of w x h, pixel(x, y) -> (r, g, b) (standard library only)."""
    raw = b"".join(b"\x00" + b"".join(bytes(pixel(x, y)) for x in range(w)) for y in range(h))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xffffffff)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) +
                chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


# where the level is: the game's collision grid starts at 0 (every coordinate must be positive), so the shapes below,
# made round (0, 0, 0) as in a modelling program, are moved there by level.txt's offset line (every coordinate of
# level.txt and of the OBJ files; "offset auto" would choose one). lights.txt's coordinates are the game's: moved here.
ORIGIN = (200.0, 200.0, 20.0)


class Mesh:
    """Quads and boxes as OBJ faces (counter-clockwise seen from outside), with UVs in world units / `tile`."""

    def __init__(self):
        self.v, self.vt, self.faces = [], [], []  # faces: (material, [(v, vt)...]); v: (x, y, z) or (x, y, z, r, g, b)

    def quad(self, mat, a, b, c, d, tile=4.0, uv_axes=None, colour=None):
        ids = []
        for p in (a, b, c, d):
            self.v.append(tuple(p) + (tuple(colour(p)) if colour else ()))
            if uv_axes is None:
                u, w = p[0] / tile, p[1] / tile
            else:
                u, w = p[uv_axes[0]] / tile, p[uv_axes[1]] / tile
            self.vt.append((u, w))
            ids.append((len(self.v), len(self.vt)))
        self.faces.append((mat, ids))

    def box(self, mat, x0, y0, z0, x1, y1, z1, top=None, colour=None):
        top = top or mat
        c = colour
        self.quad(top, (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1), colour=c)  # top
        self.quad(mat, (x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1), uv_axes=(0, 2), colour=c)  # -y
        self.quad(mat, (x1, y1, z0), (x0, y1, z0), (x0, y1, z1), (x1, y1, z1), uv_axes=(0, 2), colour=c)  # +y
        self.quad(mat, (x0, y1, z0), (x0, y0, z0), (x0, y0, z1), (x0, y1, z1), uv_axes=(1, 2), colour=c)  # -x
        self.quad(mat, (x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1), uv_axes=(1, 2), colour=c)  # +x

    def write(self, path, mtl=None, objects=None):
        with open(path, "w") as f:
            f.write("# rac1-native: the example level (examples/custom-level/make_example.py), z up, game units\n")
            if mtl:
                f.write("mtllib %s\n" % mtl)
            for p in self.v:  # (a vertex's colour after its position: "v x y z r g b", 0..1)
                f.write("v %s\n" % " ".join("%.4f" % c for c in p))
            for t in self.vt:
                f.write("vt %.4f %.4f\n" % t)
            cur = None
            for i, (mat, ids) in enumerate(self.faces):
                if objects and i in objects:
                    f.write("o %s\n" % objects[i])
                if mat != cur:
                    f.write("usemtl %s\n" % mat)
                    cur = mat
                f.write("f %s\n" % " ".join("%d/%d" % x for x in ids))


def vag(path, rate, samples):
    """A mono VAG (PS-ADPCM, the format of the disc's music) of `samples` (floats -1..1): the 0x30-byte "VAGp" header,
    then 16-byte blocks of 28 samples, each with the predictor and shift that fit it best (standard library only)."""
    coefs = ((0, 0), (60, 0), (115, -52), (98, -55), (122, -60))
    pcm = [max(-32768, min(32767, int(v * 32767))) for v in samples]
    pcm += [0] * (-len(pcm) % 28)
    out = bytearray()
    s1 = s2 = 0
    for b in range(0, len(pcm), 28):
        block = pcm[b:b + 28]
        best = None
        for f, (c1, c2) in enumerate(coefs):
            # the shift from the block's largest residual, then the block encoded with the decoder's own state
            p1, p2, peak = s1, s2, 0
            for x in block:
                peak = max(peak, abs(x - ((p1 * c1 + p2 * c2) >> 6)))
                p2, p1 = p1, x
            shift = 12
            while shift > 0 and (7 << (12 - shift)) < peak:
                shift -= 1
            p1, p2, err, nib = s1, s2, 0, []
            for x in block:
                pred = (p1 * c1 + p2 * c2) >> 6
                q = max(-8, min(7, int(round((x - pred) / float(1 << (12 - shift))))))
                y = max(-32768, min(32767, ((q << 12) >> shift) + pred))
                err += (x - y) * (x - y)
                nib.append(q & 15)
                p2, p1 = p1, y
            if best is None or err < best[0]:
                best = (err, f, shift, nib, p1, p2)
        _, f, shift, nib, s1, s2 = best
        out += bytes((f << 4 | shift, 0)) + bytes(nib[i] | nib[i + 1] << 4 for i in range(0, 28, 2))
    out += bytes((0, 7)) + bytes(14)  # (the end block)
    head = b"VAGp" + struct.pack(">IIII", 0x20, 0, len(out), rate) + bytes(12) + b"plateau".ljust(16, b"\0")
    with open(path, "wb") as f:
        f.write(head + out)


def tune(rate):
    """Eight bars of a soft arpeggio (our own), 0.25 s a note, as floats."""
    notes = [57, 60, 64, 67, 57, 60, 64, 69, 53, 57, 60, 64, 55, 59, 62, 67] * 2
    out = []
    for k, n in enumerate(notes):
        f = 440.0 * 2 ** ((n - 69) / 12.0)
        for i in range(rate // 4):
            t = i / float(rate)
            env = min(1.0, t * 40) * math.exp(-t * 5)
            out.append(0.3 * env * (math.sin(2 * math.pi * f * t) + 0.3 * math.sin(4 * math.pi * f * t)))
    return out


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join("mods", "example-plateau")
    lvl = os.path.join(out, "level")
    os.makedirs(lvl, exist_ok=True)
    with open(os.path.join(out, "mod.json"), "w") as f:
        json.dump({"name": "Example Plateau", "author": "rac1-native", "version": "1",
                   "description": "A small example level: a floor, a ramp, a raised platform and a ship pad.",
                   "kind": "level", "level": {"id": "example-plateau", "format": 1, "base": 0}}, f, indent=2)
        f.write("\n")
    with open(os.path.join(lvl, "level.txt"), "w") as f:
        f.write("# rac1-native level, format 1 (docs/mods.md, \"Level mods\")\n"
                "name Example Plateau\n"
                "name.it Altopiano d'esempio\n"
                "name.de Beispiel-Plateau\n"
                "name.es Meseta de ejemplo\n"
                "region Custom Levels\n"
                "region.it Livelli personalizzati\n"
                "region.de Eigene Level\n"
                "region.es Niveles propios\n"
                "# the OBJ files and the coordinates below are made round (0, 0, 0): moved to (200, 200, 20)\n"
                "offset %g %g %g\n"
                "hero %g %g %g 1.5708\n"
                "ship %g %g %g -1.5708\n"
                "death_height %g\n"
                "# the sky of level 3 (Kerwan), the music of our own (plateau.vag; \"music 3\" would play Kerwan's)\n"
                "sky 3\n"
                "music plateau.vag\n"
                "# objects of the base level's classes (Veldin's: 500 a bolt crate, 501 a nanotech crate, 511 an ammo crate)\n"
                "moby 500 %g %g %g\n"
                "moby 500 %g %g %g\n"
                "moby 500 %g %g %g\n"
                "moby 501 %g %g %g\n"
                "moby 511 %g %g %g\n"
                "# the 6th: the plugin's moving platform (plugin/example_plugin.c moves it; uid 6)\n"
                "moby 500 %g %g %g\n"
                "background 70 110 160\n"
                "fog 70 110 160\n" % (ORIGIN + (0, -6, 0.5, 0, 18, 0.2, -30) +
                                       tuple(c for x, y in ((4, 2), (6, 2), (8, 2), (-4, 2), (-6, 2), (-8, 10)) for c in (x, y, 0.5))))
    # the shapes: the floor 64 x 64 at z 0 (four objects), a ramp to a platform 4 high, three blocks
    mesh, coll = Mesh(), Mesh()
    objects = {}
    for k, (x0, y0) in enumerate(((-32, -32), (0, -32), (-32, 0), (0, 0))):
        objects[len(mesh.faces)] = "floor%d" % k
        for gx in range(4):
            for gy in range(4):
                a, b = x0 + gx * 8, y0 + gy * 8
                mesh.quad("checker", (a, b, 0), (a + 8, b, 0), (a + 8, b + 8, 0), (a, b + 8, 0), tile=8.0)
                coll.quad("type31", (a, b, 0), (a + 8, b, 0), (a + 8, b + 8, 0), (a, b + 8, 0))
    objects[len(mesh.faces)] = "platform"
    for m in (mesh, coll):
        mat, top = ("type31", "type31") if m is coll else ("stone", "checker")
        m.box(mat, -24, 8, 0, -12, 20, 4, top=top)  # the platform
        # the ramp: from (-18, -8, 0) up to the platform's edge (-18, 8, 4), 6 wide
        m.quad(top, (-21, -8, 0), (-15, -8, 0), (-15, 8, 4), (-21, 8, 4))
        # small blocks, their vertices coloured (warm at the bottom, cool at the top: the OBJ's vertex colours)
        grad = (lambda p: (1.0, 0.55 + 0.15 * p[2], 0.35 + 0.2 * p[2])) if m is mesh else None
        m.box(mat, 10, -14, 0, 14, -10, 1.5, colour=grad)
        m.box(mat, 16, -6, 0, 20, -2, 3, colour=grad)
        m.box(mat, 20, 4, 0, 26, 10, 1, colour=grad)
        # the ship pad
        if m is mesh:
            objects[len(mesh.faces)] = "pad"
        m.box("pad" if m is mesh else "type31", -5, 13, 0, 5, 23, 0.2)
    mesh.write(os.path.join(lvl, "meshes.obj"), mtl="meshes.mtl", objects=objects)
    coll.write(os.path.join(lvl, "collision.obj"))
    with open(os.path.join(lvl, "meshes.mtl"), "w") as f:
        f.write("# rac1-native: the example level's materials\n"
                "newmtl checker\nKd 1 1 1\nmap_Kd checker.png\n"
                "newmtl stone\nKd 1 1 1\nmap_Kd stone.png\n"
                "newmtl pad\nKd 0.85 0.55 0.15\n")
    # the modern lighting's file for the level (data/lights/levelNN.txt's format): the sun, and two lamps by the platform
    # and the blocks ("light x y z  r g b  intensity radius flicker on")
    with open(os.path.join(lvl, "lights.txt"), "w") as f:
        ox, oy, oz = ORIGIN
        f.write("# rac1-native: the example level's lights (our choices)\n"
                "sun 0.9 30\n"
                "light %g %g %g  1.000 0.700 0.400  3.000 10.000 0.000 1\n"
                "light %g %g %g  0.400 0.700 1.000  3.000 10.000 0.000 1\n" % (ox - 18, oy + 22, oz + 4, ox + 20, oy - 10, oz + 2))
    vag(os.path.join(lvl, "plateau.vag"), 22050, tune(22050))
    png(os.path.join(lvl, "checker.png"), 64, 64,
        lambda x, y: (200, 200, 190) if ((x // 32) + (y // 32)) % 2 == 0 else (120, 150, 110))
    png(os.path.join(lvl, "stone.png"), 32, 32,
        lambda x, y: tuple(int(c * (0.85 + 0.15 * math.sin(x * 0.7) * math.cos(y * 0.9))) for c in (150, 140, 130)))
    # the plugin (its code: examples/custom-level/plugin/, copied as it is; the setup builds it)
    here = os.path.dirname(os.path.abspath(__file__))
    os.makedirs(os.path.join(out, "plugin"), exist_ok=True)
    for name in ("CMakeLists.txt", "example_plugin.c"):
        with open(os.path.join(here, "plugin", name), "rb") as src, open(os.path.join(out, "plugin", name), "wb") as dst:
            dst.write(src.read())
    print("wrote", out)


if __name__ == "__main__":
    main()
